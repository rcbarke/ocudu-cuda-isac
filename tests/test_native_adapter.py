"""Check the adapter builder against synthetic OCUDU build trees. No compiler, source or GPU is needed."""

import hashlib
import importlib.util
import json
from pathlib import Path
import shlex
import sys
import tempfile
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("native_adapter", ROOT / "scripts/native_adapter.py")
native_adapter = importlib.util.module_from_spec(spec)
sys.modules["native_adapter"] = native_adapter
spec.loader.exec_module(native_adapter)
AdapterError = native_adapter.AdapterError

TARGET_DIR = "tests/integrationtests/phy/upper/channel_processors"
# The recipe CMake writes for pusch_e2e_pipeline_test in a CUDA Release build on a DGX Spark.
SPARK_FLAGS = """# CMAKE generated file: DO NOT EDIT!
# Generated by "Unix Makefiles" Generator, CMake Version 3.28

# compile CXX with /usr/bin/c++
CXX_DEFINES = -DENABLE_CUDA

CXX_INCLUDES = -I{source} -I{source}/lib/phy/upper/channel_coding/ldpc -I{source}/include -I{source}/external/fmt/include -I{source}/external -isystem /usr/local/cuda/targets/sbsa-linux/include

CXX_FLAGS =  -Wall -Werror -Wno-error=array-bounds -Wshadow -fno-rtti -mcpu=neoverse-v2 -O3 -DNDEBUG -fno-trapping-math -fno-math-errno -DBUILD_TYPE_RELEASE -std=gnu++17
"""
SPARK_LINK = ("/usr/bin/c++  -Wall -Werror -Wno-error=array-bounds -Wshadow -fno-rtti -mcpu=neoverse-v2 -O3 -DNDEBUG "
              "-fno-trapping-math -fno-math-errno -DBUILD_TYPE_RELEASE "
              "CMakeFiles/pusch_e2e_pipeline_test.dir/pusch_e2e_pipeline_test.cpp.o -o pusch_e2e_pipeline_test  "
              "-Wl,-rpath,/usr/local/cuda-13.5/targets/sbsa-linux/lib: libocudu_pxsch_bler_test_helpers.a "
              "../../../../../lib/phy/upper/libocudu_upper_phy.a ../../../../../lib/phy/cuda/libocudu_phy_cuda.a "
              "/usr/local/cuda-13.5/targets/sbsa-linux/lib/libcudart.so ../../../../../lib/phy/upper/libocudu_upper_phy.a "
              "/usr/lib/aarch64-linux-gnu/libfftw3f.so -ldl -L/usr/local/cuda/targets/sbsa-linux/lib/stubs -lcudadevrt\n")
ARCHIVES = (f"{TARGET_DIR}/libocudu_pxsch_bler_test_helpers.a", "lib/phy/upper/libocudu_upper_phy.a",
            "lib/phy/cuda/libocudu_phy_cuda.a")


class RecipeParsingTests(unittest.TestCase):
    def test_compile_flags_keep_the_pinned_options_and_drop_only_werror(self):
        flags = native_adapter.parse_flags(SPARK_FLAGS.format(source="/s"))
        self.assertEqual(flags["definitions"], ["ENABLE_CUDA"])
        self.assertEqual(flags["includes"], ["/s", "/s/lib/phy/upper/channel_coding/ldpc", "/s/include",
                                             "/s/external/fmt/include", "/s/external"])
        self.assertEqual(flags["system_includes"], ["/usr/local/cuda/targets/sbsa-linux/include"])
        self.assertEqual(flags["options"], ["-Wall", "-Wno-error=array-bounds", "-Wshadow", "-fno-rtti",
                                            "-mcpu=neoverse-v2", "-O3", "-DNDEBUG", "-fno-trapping-math",
                                            "-fno-math-errno", "-DBUILD_TYPE_RELEASE", "-std=gnu++17"])

    def test_unreadable_compile_flags_are_refused(self):
        for text, message in (("CXX_FLAGS = -O3\n", "does not hold CXX_DEFINES"),
                              (SPARK_FLAGS.format(source="/s").replace("-DENABLE_CUDA", "ENABLE_CUDA"), "definition"),
                              (SPARK_FLAGS.format(source="/s").replace("-isystem /usr", "-iquote /usr"), "include")):
            with self.assertRaisesRegex(AdapterError, message):
                native_adapter.parse_flags(text)

    def test_link_line_splits_into_options_archives_and_other_items(self):
        with tempfile.TemporaryDirectory() as temporary:
            build = Path(temporary)
            for name in ARCHIVES:
                (build / name).parent.mkdir(parents=True, exist_ok=True)
                (build / name).write_text("archive")
            link = native_adapter.parse_link(SPARK_LINK, build / TARGET_DIR)
            self.assertEqual(link["compiler"], "/usr/bin/c++")
            # Warnings and definitions stay with the compile step. Machine and code generation
            # options reach the link as they do for the pinned test.
            self.assertEqual(link["options"], ["-fno-rtti", "-mcpu=neoverse-v2", "-O3", "-fno-trapping-math",
                                               "-fno-math-errno"])
            self.assertEqual(link["archives"], [str(build / name) for name in ARCHIVES])  # absolute, once each
            self.assertEqual(link["items"], ["-Wl,-rpath,/usr/local/cuda-13.5/targets/sbsa-linux/lib:",
                                             "/usr/local/cuda-13.5/targets/sbsa-linux/lib/libcudart.so",
                                             "/usr/lib/aarch64-linux-gnu/libfftw3f.so", "-ldl",
                                             "-L/usr/local/cuda/targets/sbsa-linux/lib/stubs", "-lcudadevrt"])
            (build / ARCHIVES[2]).unlink()
            with self.assertRaisesRegex(AdapterError, "libocudu_phy_cuda.a. Build it"):
                native_adapter.parse_link(SPARK_LINK, build / TARGET_DIR)

    def test_unreadable_link_lines_are_refused(self):
        with tempfile.TemporaryDirectory() as temporary:
            target = Path(temporary)
            cases = (("", "exactly one link command"), (SPARK_LINK + SPARK_LINK, "exactly one link command"),
                     ("/usr/bin/c++ a.o\n", "no output option"),
                     ("/usr/bin/c++ a.o -o gnb liba.a\n", "expected pusch_e2e_pipeline_test"),
                     ("/usr/bin/c++ a.o -o pusch_e2e_pipeline_test b.o\n", "links the object"),
                     ("/usr/bin/c++ a.o -o pusch_e2e_pipeline_test -ldl\n", "no static library"))
            for text, message in cases:
                with self.assertRaisesRegex(AdapterError, message):
                    native_adapter.parse_link(text, target)

    def test_cmake_values_are_quoted_one_argument_each(self):
        text = native_adapter.cmake_list("NAME", ["-O3", "/a b/c", 'say "x"', "a;b", "$ENV{HOME}", "back\\slash"])
        self.assertEqual(text, 'set(NAME\n  "-O3"\n  "/a b/c"\n  "say \\"x\\""\n  "a\\;b"\n  "\\$ENV{HOME}"\n'
                               '  "back\\\\slash")\n')
        self.assertEqual(native_adapter.cmake_list("EMPTY", []), "set(EMPTY)\n")


class ImportTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve() / "host checkout"
        self.source = self.root / "ext/ocudu"
        self.build = self.root / "build/ocudu-spark"
        (self.source / TARGET_DIR).mkdir(parents=True)
        (self.source / TARGET_DIR / "pxsch_bler_test_factories.h").write_text("// helper\n")
        recipe = self.build / TARGET_DIR / "CMakeFiles/pusch_e2e_pipeline_test.dir"
        recipe.mkdir(parents=True)
        # The checkout path holds a space, which CMake escapes in the recipe.
        (recipe / "flags.make").write_text(SPARK_FLAGS.format(source=shlex.quote(str(self.source))))
        (recipe / "link.txt").write_text(SPARK_LINK)
        for name in ARCHIVES:
            (self.build / name).parent.mkdir(parents=True, exist_ok=True)
            (self.build / name).write_text("archive")
        (self.build / TARGET_DIR / "pusch_e2e_pipeline_test").write_text("executable")
        self.cache = self.build / "CMakeCache.txt"
        self.cache.write_text(f"CMAKE_BUILD_TYPE:STRING=Release\nCMAKE_GENERATOR:INTERNAL=Unix Makefiles\n"
                              f"CMAKE_CXX_COMPILER:FILEPATH=/usr/bin/g++-13\n"
                              f"CMAKE_HOME_DIRECTORY:INTERNAL={self.source}\n")

    def test_import_file_carries_the_pinned_recipe(self):
        text, facts = native_adapter.pin_import(self.build, self.source)
        self.assertTrue(text.isascii())
        # The compiler is the one in the cache, also where the link line starts with another driver.
        for line in ('set(OCUDU_PIN_CXX_COMPILER\n  "/usr/bin/g++-13")', 'set(OCUDU_PIN_CXX_DEFINES\n  "ENABLE_CUDA")',
                     f'set(OCUDU_PIN_TEST_SOURCE_DIR\n  "{self.source / TARGET_DIR}")',
                     f'set(OCUDU_PIN_SYSTEM_INCLUDES\n  "/usr/local/cuda/targets/sbsa-linux/include")',
                     f'  "{self.build / ARCHIVES[2]}"', '  "-mcpu=neoverse-v2"', '  "-lcudadevrt")'):
            self.assertIn(line, text)
        self.assertIn(f'set(OCUDU_PIN_INCLUDES\n  "{self.source}"\n  "{self.source}/lib/phy/upper/channel_coding/ldpc"', text)
        self.assertNotIn('"-Werror"', text)
        self.assertEqual((facts["cuda"], facts["archives"], facts["build_type"], facts["compiler"],
                          facts["linker_driver"]), (True, 3, "Release", "/usr/bin/g++-13", "/usr/bin/c++"))
        self.assertEqual(facts["pin_test_sha256"], hashlib.sha256(b"executable").hexdigest())
        self.assertEqual(native_adapter.pin_import(self.build, self.source)[0], text)  # the same bytes on repeat
        self.cache.write_text(self.cache.read_text().replace("CMAKE_CXX_COMPILER:FILEPATH=/usr/bin/g++-13\n", ""))
        self.assertIn('set(OCUDU_PIN_CXX_COMPILER\n  "/usr/bin/c++")', native_adapter.pin_import(self.build, self.source)[0])

    def test_a_build_that_is_not_the_accepted_recipe_is_refused(self):
        def rewrite(old, new):
            self.cache.write_text(self.cache.read_text().replace(old, new))

        def recipe():
            return self.build / TARGET_DIR / "CMakeFiles/pusch_e2e_pipeline_test.dir"

        cases = (
            (lambda: rewrite("Unix Makefiles", "Ninja"), "generator 'Ninja'"),
            (lambda: rewrite(str(self.source), "/another/source"), "not from the locked source"),
            (lambda: (recipe() / "link.txt").unlink(), "has no .*link.txt"),
            (lambda: (recipe() / "flags.make").unlink(), "has no .*flags.make"),
            (lambda: (self.source / TARGET_DIR / "pxsch_bler_test_factories.h").unlink(), "no test helpers"),
            (lambda: self.cache.unlink(), "not a configured OCUDU build"),
        )
        for change, message in cases:
            self.setUp()  # a fresh tree for every case
            change()
            with self.assertRaisesRegex(AdapterError, message):
                native_adapter.pin_import(self.build, self.source)

    def test_accepted_build_is_read_from_the_environment_link(self):
        bin_dir = self.root / "isac/bin"
        bin_dir.mkdir(parents=True)
        with self.assertRaisesRegex(AdapterError, "make accept-s1.1"):
            native_adapter.accepted_build(bin_dir)
        (bin_dir / "pusch_e2e_pipeline_test").symlink_to(self.build / TARGET_DIR / "pusch_e2e_pipeline_test")
        self.assertEqual(native_adapter.accepted_build(bin_dir), self.build)
        (bin_dir / "pusch_e2e_pipeline_test").unlink()
        (bin_dir / "pusch_e2e_pipeline_test").symlink_to(self.cache)  # a link to something else
        with self.assertRaisesRegex(AdapterError, "not a link into an OCUDU build"):
            native_adapter.accepted_build(bin_dir)


class ReceiptTests(unittest.TestCase):
    """A receipt is trusted only while the executable, the adapter sources and the OCUDU build match it."""

    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        self.adapter = self.root / "native/ocudu_adapter"
        (self.adapter / "fixtures").mkdir(parents=True)
        (self.adapter / "fixtures/grant_fixture.cpp").write_text("int main() {}\n")
        # The observation ring is built with the adapter and linked by it: the receipt binds it too.
        self.ring = self.root / "native/obs_ring"
        (self.ring / "src").mkdir(parents=True)
        (self.ring / "src/ring.cpp").write_text("// ring\n")
        self.ocudu = self.root / "build/ocudu-spark"
        recipe = self.ocudu / TARGET_DIR / "CMakeFiles/pusch_e2e_pipeline_test.dir"
        recipe.mkdir(parents=True)
        (recipe / "flags.make").write_text("flags")
        (recipe / "link.txt").write_text("link")
        (self.ocudu / "isac-native.json").write_text("{}")
        self.build = self.root / "build/ocudu-adapter"
        (self.build / "fixtures").mkdir(parents=True)
        self.executable = self.build / "fixtures/grant_fixture"
        self.executable.write_text("binary")
        for name, value in (("ROOT", self.root), ("ADAPTER", self.adapter), ("RING", self.ring)):
            patcher = mock.patch.object(native_adapter, name, value)
            patcher.start()
            self.addCleanup(patcher.stop)
        digest = native_adapter.digest
        self.receipt = {
            "schema": native_adapter.RECEIPT_SCHEMA, "ocudu_build": str(self.ocudu),
            "ocudu_receipt_sha256": digest(self.ocudu / "isac-native.json"), "sources": native_adapter.sources(),
            "executables": {"grant_fixture": {"path": str(self.executable), "sha256": digest(self.executable)}},
            "pin": {"flags_make_sha256": digest(recipe / "flags.make"), "link_txt_sha256": digest(recipe / "link.txt")},
        }
        (self.build / native_adapter.RECEIPT).write_text(json.dumps(self.receipt))
        self.recipe = recipe

    def test_an_untouched_build_verifies(self):
        self.assertEqual(native_adapter.verified_receipt(self.build), self.receipt)
        self.assertEqual(list(self.receipt["sources"]),
                         ["native/ocudu_adapter/fixtures/grant_fixture.cpp", "native/obs_ring/src/ring.cpp"])

    def test_every_change_after_the_build_is_detected(self):
        cases = (
            (lambda: self.executable.write_text("another binary"), "executable grant_fixture differs"),
            (lambda: (self.adapter / "fixtures/grant_fixture.cpp").write_text("int main() { return 1; }\n"),
             "adapter sources changed"),
            (lambda: (self.adapter / "fixtures/new.cpp").write_text("\n"), "adapter sources changed"),
            (lambda: (self.ring / "src/ring.cpp").write_text("// another ring\n"), "adapter sources changed"),
            (lambda: (self.ocudu / "isac-native.json").write_text('{"rebuilt": true}'), "OCUDU build was rebuilt"),
            (lambda: (self.recipe / "link.txt").write_text("other link"), "OCUDU build was reconfigured"),
            (lambda: (self.build / native_adapter.RECEIPT).unlink(), "no adapter receipt"),
            (lambda: (self.build / native_adapter.RECEIPT).write_text('{"schema": "other"}'), "is not a"),
        )
        for change, message in cases:
            self.setUp()
            change()
            with self.assertRaisesRegex(AdapterError, message):
                native_adapter.verified_receipt(self.build)


class BuildRefusalTests(unittest.TestCase):
    def run_build(self, *arguments):
        with mock.patch("sys.stderr") as stderr:
            status = native_adapter.main(["build", *arguments])
        return status, "".join(call.args[0] for call in stderr.write.call_args_list)

    def test_a_build_without_a_sprint_one_receipt_is_refused(self):
        with tempfile.TemporaryDirectory() as temporary:
            ocudu = Path(temporary) / "ocudu-build"
            ocudu.mkdir()
            status, message = self.run_build("--ocudu-build-dir", str(ocudu), "--build-dir",
                                             str(Path(temporary) / "adapter"))
            self.assertEqual(status, 1)
            self.assertIn("is not a build that 'make accept-s1.1' produced", message)
            self.assertFalse((Path(temporary) / "adapter").exists())  # refused before anything is written

    def test_an_adapter_build_inside_the_ocudu_build_or_source_is_refused(self):
        with tempfile.TemporaryDirectory() as temporary:
            ocudu = Path(temporary) / "ocudu-build"
            ocudu.mkdir()
            status, message = self.run_build("--ocudu-build-dir", str(ocudu), "--build-dir", str(ocudu / "adapter"),
                                             "--no-receipt")
            self.assertEqual(status, 1)
            self.assertIn("lies inside", message)
            self.assertEqual(list(ocudu.iterdir()), [])


class PatchedReceiverTests(unittest.TestCase):
    """Sprint 5.2: the adapter with the O3 route is built only against a build of the patched receiver."""

    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.build = Path(temporary.name) / "ocudu-o3"
        self.build.mkdir()
        self.adapter = Path(temporary.name) / "adapter"

    def run_build(self, *arguments):
        with mock.patch("sys.stderr") as stderr:
            status = native_adapter.main(["build", "--build-dir", str(self.adapter), *arguments])
        return status, "".join(call.args[0] for call in stderr.write.call_args_list)

    def series(self):
        return native_adapter.receiver_patch.identity(native_adapter.receiver_patch.load_series())

    def test_the_route_needs_the_receipt_of_a_patched_receiver_with_this_series(self):
        status, said = self.run_build("--o3", "--ocudu-build-dir", str(self.build))
        self.assertEqual(status, 1)
        self.assertIn("it is not a build of the patched receiver", said)
        (self.build / "isac-native.json").write_text(json.dumps({"source": "/somewhere", "commit": "0" * 40}))
        status, said = self.run_build("--o3", "--ocudu-build-dir", str(self.build))
        self.assertEqual(status, 1)
        self.assertIn("is a build of the unpatched receiver: its receipt names no patch", said)
        other = dict(self.series(), series_sha256="0" * 64)
        (self.build / "isac-native.json").write_text(json.dumps({"source": "/somewhere", "patch": other}))
        status, said = self.run_build("--o3", "--ocudu-build-dir", str(self.build))
        self.assertEqual(status, 1)
        self.assertIn("was built with another patch series than patches/ocudu/ holds now", said)
        # The series is the right one and the tree it names is not the patched tree.
        (self.build / "isac-native.json").write_text(json.dumps({"source": str(self.build), "patch": self.series()}))
        status, said = self.run_build("--o3", "--ocudu-build-dir", str(self.build))
        self.assertEqual(status, 1)
        self.assertIn("is not the patched receiver source of the series", said)
        self.assertFalse(self.adapter.exists())

    def test_the_control_adapter_is_never_linked_against_the_patched_receiver(self):
        (self.build / "isac-native.json").write_text(json.dumps({"source": "/somewhere", "patch": self.series()}))
        status, said = self.run_build("--ocudu-build-dir", str(self.build))
        self.assertEqual(status, 1)
        self.assertIn("is the build of the patched receiver. Build the adapter against it with --o3", said)
        self.assertFalse(self.adapter.exists())

    def test_the_two_adapters_have_their_own_directories_and_a_route_is_required_where_asked(self):
        self.assertEqual(native_adapter.DEFAULT_BUILD.name, "ocudu-adapter")
        self.assertEqual(native_adapter.DEFAULT_BUILD_O3.name, "ocudu-adapter-o3")
        self.assertEqual(native_adapter.DEFAULT_OCUDU_O3.name, "ocudu-spark-o3")
        receipt = {"schema": native_adapter.RECEIPT_SCHEMA, "executables": {}, "sources": native_adapter.sources(),
                   "ocudu_build": str(self.build), "ocudu_receipt_sha256": None,
                   "pin": {"link_txt_sha256": "x", "flags_make_sha256": "y"}}
        with mock.patch.object(native_adapter, "verified_receipt", return_value=receipt), \
                mock.patch("sys.stderr") as stderr, mock.patch("sys.stdout"):
            self.assertEqual(native_adapter.main(["verify", "--build-dir", str(self.adapter)]), 0)
            self.assertEqual(native_adapter.main(["verify", "--o3", "--build-dir", str(self.adapter)]), 1)
        self.assertIn("this adapter build has no O3 route",
                      "".join(call.args[0] for call in stderr.write.call_args_list))


class AdapterTreeTests(unittest.TestCase):
    def test_adapter_files_are_ascii_and_keep_the_pinned_fixture_calls(self):
        tree = ROOT / "native/ocudu_adapter"
        for path in (tree / "CMakeLists.txt", tree / "fixtures/CMakeLists.txt", tree / "fixtures/grant_fixture.cpp",
                     ROOT / "scripts/native_adapter.py"):
            self.assertTrue(path.read_bytes().isascii(), path)
        source = (tree / "fixtures/grant_fixture.cpp").read_text()
        # The same factory helper and the same PDU fields as run_e2e_pipeline_test, with CRB 0 as
        # the DM-RS reference point.
        for text in ('create_sw_pdsch_processor_factory(*executor, max_nof_threads + 1, "", "auto")',
                     "pdsch_processor::pdu_t::CRB0", "pdsch_pdu.tbs_lbrm                    = tbs_lbrm_default",
                     "get_sch_to_dmrs_ratio_dB(grant.cdm_groups)", "make_wideband(make_identity(grant.layers))",
                     "tbs_calculator_calculate(tbs_config)"):
            self.assertIn(text, source)
        self.assertNotIn("std::random_device", source)  # the payload comes from the record
        cmake = (tree / "CMakeLists.txt").read_text()
        self.assertIn("-Wl,--start-group ${OCUDU_PIN_ARCHIVES} -Wl,--end-group", cmake)


